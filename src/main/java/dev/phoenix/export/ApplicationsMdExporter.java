package dev.phoenix.export;

import dev.phoenix.domain.Application;
import dev.phoenix.domain.Job;
import dev.phoenix.domain.Score;

import java.time.Instant;
import java.time.ZoneOffset;
import java.util.Comparator;
import java.util.List;

/** The applications log: every job that reached approval or later, oldest first, with a submitted total. */
public final class ApplicationsMdExporter {

    public String render(ExportSnapshot snapshot) {
        List<Job> engaged = snapshot.jobs().stream()
                .filter(j -> j.state().isEngaged() || snapshot.applications().containsKey(j.id()))
                .sorted(Comparator.comparing((Job j) -> when(j, snapshot)).thenComparingLong(Job::id))
                .toList();
        StringBuilder md = new StringBuilder("# Applications\n\n")
                .append("Generated by `phoenix export`; the engine's database is the source of truth.\n\n")
                .append("| # | Date | Company | Role | Job ID | Fit % | Status | Notes |\n")
                .append("|---|------|---------|------|--------|-------|--------|-------|\n");
        int n = 0;
        int submitted = 0;
        for (Job job : engaged) {
            Score score = snapshot.scores().get(job.id());
            Application application = snapshot.applications().get(job.id());
            n++;
            if (job.state().isApplied()) {
                submitted++;
            }
            md.append("| ").append(n)
                    .append(" | ").append(when(job, snapshot).atZone(ZoneOffset.UTC).toLocalDate())
                    .append(" | ").append(MarkdownCells.of(job.company()))
                    .append(" | ").append(MarkdownCells.of(job.title()))
                    .append(" | ").append(MarkdownCells.of(job.extId()))
                    .append(" | ").append(score == null ? "" : score.fitPct())
                    .append(" | ").append(LegacyStatusLabels.of(job.state()))
                    .append(" | ").append(application == null ? "" : MarkdownCells.of(application.note()))
                    .append(" |\n");
        }
        return md.append("\n**Submitted: ").append(submitted).append("**\n").toString();
    }

    private static Instant when(Job job, ExportSnapshot snapshot) {
        Application application = snapshot.applications().get(job.id());
        return application != null && application.submittedAt() != null ? application.submittedAt() : job.firstSeen();
    }
}
